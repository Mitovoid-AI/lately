// Writes src/legal/licenses.ts: the open-source notices shown at Account > Open-source licences.
// Run after adding, removing or updating a dependency: node scripts/build-licenses.js
// It reads package.json's dependencies (what ships in the app; dev tools don't), each package's
// own package.json in node_modules, and the SIL Open Font License that the bundled font packages
// carry (the OFL asks for its text to travel with the fonts). No network, no extra packages.
/* global __dirname */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));
const pkgDir = (name) => path.join(root, "node_modules", ...name.split("/"));

/** "MIT", { type: "MIT" }, or an old-style licenses array → one SPDX-ish string. */
function licenseOf(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license.type === "string") return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(" OR ");
  return "See the package";
}

/** The homepage, else the repository as an https link; null when the package names neither. */
function urlOf(pkg) {
  if (typeof pkg.homepage === "string" && /^https?:\/\//.test(pkg.homepage)) return pkg.homepage;
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  if (typeof repo !== "string") return null;
  return repo
    .replace(/^git\+/, "")
    .replace(/^github:/, "https://github.com/")
    .replace(/^git:\/\//, "https://")
    .replace(/^git@github\.com:/, "https://github.com/")
    .replace(/^(?!https?:\/\/)([\w.-]+\/[\w.-]+)$/, "https://github.com/$1")
    .replace(/\.git$/, "");
}

const app = readJson(path.join(root, "package.json"));
const names = Object.keys(app.dependencies ?? {}).sort();

const packages = names.map((name) => {
  const file = path.join(pkgDir(name), "package.json");
  if (!fs.existsSync(file)) throw new Error(`${name} is not installed: run npm install first`);
  const pkg = readJson(file);
  return { name, version: pkg.version, license: licenseOf(pkg), url: urlOf(pkg) };
});

// Google Fonts packages ship the font's own licence as LICENSE_FONT: the copyright line(s),
// then the OFL text, which is the same for every family (checked below).
const OFL_START = /^-+\s*\n\s*SIL OPEN FONT LICENSE/m;
let oflText = null;
const fonts = names
  .filter((name) => name.startsWith("@expo-google-fonts/"))
  .map((name) => {
    const text = fs.readFileSync(path.join(pkgDir(name), "LICENSE_FONT"), "utf8").replace(/\r\n/g, "\n");
    const start = text.search(OFL_START);
    if (start < 0) throw new Error(`${name}/LICENSE_FONT is not the SIL Open Font License`);
    const body = text.slice(start).trim();
    if (oflText === null) oflText = body;
    else if (body !== oflText) throw new Error(`${name} carries a different OFL text: check it by hand`);
    const copyright = text.slice(0, text.indexOf("This Font Software is licensed")).trim();
    const family = readJson(path.join(pkgDir(name), "metadata.json")).family;
    return { family, copyright, license: "SIL Open Font License 1.1", source: name };
  });
if (oflText === null) throw new Error("No font package found: the OFL text has nowhere to come from");

// The icon fonts come inside @expo/vector-icons, which ships no licence file for them, so their
// notices are written here from the projects' own licences.
const iconFonts = [
  {
    family: "Font Awesome 4.7 (icons)",
    copyright: "Font Awesome by Dave Gandy, https://fontawesome.com",
    license: "SIL Open Font License 1.1",
    source: "@expo/vector-icons",
  },
  {
    family: "Ionicons (icons)",
    copyright: "Copyright (c) 2015-present Ionic, https://ionic.io",
    license: "MIT",
    source: "@expo/vector-icons",
  },
];

let out = "// Generated by scripts/build-licenses.js from package.json and node_modules — do not edit by hand.\n";
out += "// Re-run after changing dependencies: node scripts/build-licenses.js\n\n";
out += "export interface PackageLicense {\n  name: string;\n  version: string;\n  license: string;\n  url: string | null;\n}\n\n";
out += "export interface FontLicense {\n  family: string;\n  copyright: string;\n  license: string;\n  /** The package that bundles it. */\n  source: string;\n}\n\n";
out += "export const PACKAGES: PackageLicense[] = [\n";
for (const p of packages) out += `  ${JSON.stringify(p)},\n`;
out += "];\n\n";
out += "export const FONTS: FontLicense[] = [\n";
for (const f of [...fonts, ...iconFonts]) out += `  ${JSON.stringify(f)},\n`;
out += "];\n\n";
out += `export const OFL_TEXT = ${JSON.stringify(oflText)};\n`;

fs.writeFileSync(path.join(root, "src", "legal", "licenses.ts"), out);
console.log(`wrote src/legal/licenses.ts (${packages.length} packages, ${fonts.length + iconFonts.length} fonts)`);
