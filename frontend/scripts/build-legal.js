// Bundles legal/*.md into src/legal/documents.ts (Metro can't import .md as text).
// Run after editing either document: node scripts/build-legal.js
// src/legal/__tests__/legal.test.tsx fails if the bundle and the .md files drift apart.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const docs = { privacy: "Privacy Policy", terms: "Terms of Service" };

let out = "// Generated by scripts/build-legal.js from legal/*.md — do not edit by hand.\n\n";
out += "export type LegalDoc = " + Object.keys(docs).map((d) => JSON.stringify(d)).join(" | ") + ";\n\n";
out += "export const LEGAL_DOCS: Record<LegalDoc, { title: string; markdown: string }> = {\n";
for (const [doc, title] of Object.entries(docs)) {
  const md = fs.readFileSync(path.join(root, "legal", `${doc}.md`), "utf8").replace(/\r\n/g, "\n");
  out += `  ${doc}: {\n    title: ${JSON.stringify(title)},\n    markdown: ${JSON.stringify(md)},\n  },\n`;
}
out += "};\n";
fs.writeFileSync(path.join(root, "src", "legal", "documents.ts"), out);
console.log("wrote src/legal/documents.ts");
